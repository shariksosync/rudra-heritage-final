export function Button({
  children,
  variant = "primary",
  size = "default",
  className = "",
  type = "button",
  ...props
}) {
  const styles = {
    primary: "border border-primary bg-primary text-primary-foreground hover:bg-primary/90",
    outline: "border border-primary bg-transparent text-primary hover:bg-primary hover:text-primary-foreground",
    ghost: "border border-transparent text-foreground hover:bg-muted",
  };
  const sizes = {
    default: "min-h-11 px-5 py-2.5 text-sm",
    small: "min-h-9 px-3 py-2 text-xs",
  };
  return (
    <button
      type={type}
      className={`inline-flex items-center justify-center gap-2 rounded-sm font-semibold transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 ${styles[variant] || styles.primary} ${sizes[size] || sizes.default} ${className}`}
      {...props}
    >
      {children}
    </button>
  );
}

export function formatPrice(value) {
  const amount = Number(value) || 0;
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(amount);
}